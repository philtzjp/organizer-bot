import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import { describe, it } from "node:test"
import { cleanFooters } from "./footers.ts"
import type { GitHubRequest, GitHubResponse } from "./github.ts"
import { readFooterTarget } from "./index.ts"

const conventions_yml = readFileSync(new URL("../../../packages/conventions/fixtures/conventions.yml", import.meta.url), "utf8")
const repo = "/repos/example-org/app"

const createFakeGitHub = (): { request: GitHubRequest, calls: { method: string, path: string, body: unknown }[] } => {
    const calls: { method: string, path: string, body: unknown }[] = []
    const request: GitHubRequest = async (method, path, body) => {
        calls.push({ method, path, body })
        if (method === "GET" && path === `${repo}/contents/.github/conventions.yml`) {
            return { status: 200, body: conventions_yml } satisfies GitHubResponse
        }
        return { status: method === "DELETE" ? 204 : 200, body: {} }
    }
    return { request, calls }
}

const base = { owner: "example-org", repository: "app" }
const body = "✳︎ Anthropic Claude Opus 5.5\n\n## 背景\n\n理由を書く。"

describe("cleanFooters", () => {
    it("Issue の本文からフッターを取り除いて書き直す", async () => {
        const fake = createFakeGitHub()
        const result = await cleanFooters(fake.request, { ...base, kind: "issue", id: 3, author: "alice", body: `${body}\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)` })
        assert.equal(result, "stripped")
        assert.deepEqual(fake.calls.at(-1), { method: "PATCH", path: `${repo}/issues/3`, body: { body } })
    })

    it("PR とコメントは、それぞれの API で書き直す", async () => {
        const footer = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
        const pull_request = createFakeGitHub()
        await cleanFooters(pull_request.request, { ...base, kind: "pull_request", id: 5, author: "alice", body: `${body}${footer}` })
        assert.equal(pull_request.calls.at(-1)?.path, `${repo}/pulls/5`)
        const comment = createFakeGitHub()
        await cleanFooters(comment.request, { ...base, kind: "comment", id: 99, author: "alice", body: `${body}${footer}` })
        assert.equal(comment.calls.at(-1)?.path, `${repo}/issues/comments/99`)
    })

    it("フッターがなければ書き直さない", async () => {
        const fake = createFakeGitHub()
        const result = await cleanFooters(fake.request, { ...base, kind: "issue", id: 3, author: "alice", body })
        assert.equal(result, "unchanged")
        assert.ok(!fake.calls.some((call) => call.method === "PATCH"))
    })

    it("閉じるときのコメントは、書いた人によらず丸ごと消す", async () => {
        for (const text of [
            "#118 の作り直しで、apps/bench を捨てたため閉じます。",
            `${body.replace("理由を書く。", "- #2 がマージされたので、この Issue を閉じます")}\n\n## 作業範囲\n\n- 結果を書く`,
            "受け入れ条件をすべて満たしたので閉じる。数字の差し替えは #187。",
            "Closing this issue as completed.",
        ]) {
            const fake = createFakeGitHub()
            const result = await cleanFooters(fake.request, { ...base, kind: "comment", id: 7, author: "alice", body: text })
            assert.equal(result, "deleted", text)
            assert.deepEqual(fake.calls.at(-1), { method: "DELETE", path: `${repo}/issues/comments/7`, body: undefined })
        }
    })

    it("閉じることに触れただけのコメントは消さない", async () => {
        for (const text of [
            "- 差分に前の名前と閉じたウィンドウを書くようにした",
            "- 閉じたときに未達だった、前後の時間の比較を行った",
            "- [ ] 次のリポジトリを作ったときに確かめて閉じる",
            "子の Issue がすべて閉じた。",
        ]) {
            const fake = createFakeGitHub()
            const result = await cleanFooters(fake.request, { ...base, kind: "comment", id: 7, author: "alice", body: text })
            assert.equal(result, "unchanged", text)
            assert.ok(!fake.calls.some((call) => call.method === "DELETE"), text)
        }
    })

    it("Issue と PR の本文は、閉じるときの形に当たっても消さない", async () => {
        const fake = createFakeGitHub()
        const result = await cleanFooters(fake.request, { ...base, kind: "issue", id: 3, author: "alice", body: "重複なので閉じます。" })
        assert.equal(result, "unchanged")
        assert.ok(!fake.calls.some((call) => call.method === "DELETE"))
    })

    it("vercel[bot] のコメントは丸ごと消す", async () => {
        const fake = createFakeGitHub()
        const result = await cleanFooters(fake.request, { ...base, kind: "comment", id: 42, author: "vercel[bot]", body: "[vc]: #abc" })
        assert.equal(result, "deleted")
        assert.deepEqual(fake.calls.at(-1), { method: "DELETE", path: `${repo}/issues/comments/42`, body: undefined })
    })
})

describe("readFooterTarget", () => {
    const repository = { name: "app", owner: { login: "example-org" } }
    const common = { installation: { id: 1 }, sender: { login: "alice" }, repository }

    it("コメントの作成と編集を対象にする", () => {
        const event = { ...common, action: "created", comment: { id: 7, body: "x", user: { login: "alice" } } }
        assert.deepEqual(readFooterTarget("issue_comment", event), { owner: "example-org", repository: "app", kind: "comment", id: 7, body: "x", author: "alice" })
    })

    it("閉じたときやラベルのときは対象にしない", () => {
        const event = { ...common, action: "closed", issue: { number: 3, state: "closed", title: "docs(docs): x を書く", body: "x", user: { login: "alice" } } }
        assert.equal(readFooterTarget("issues", event), undefined)
    })
})
